"""Build a review-ready YouTube Shorts package on disk."""

from __future__ import annotations

import hashlib
import json
import re
import unicodedata
from dataclasses import asdict
from pathlib import Path
from urllib.parse import urlparse

from . import GENERATOR_NAME, __version__
from .feeds import Headline
from .render import (
    THUMBNAIL_HEIGHT,
    THUMBNAIL_WIDTH,
    VERTICAL_HEIGHT,
    VERTICAL_WIDTH,
    render_story_frame,
    render_thumbnail,
    write_svg,
)
from .script import Script

PACKAGE_SCHEMA_VERSION = 1
REQUIRED_ARTIFACTS = (
    "frame-01-hook.svg",
    "frame-02-context.svg",
    "frame-03-punchline.svg",
    "thumbnail.svg",
    "script.md",
    "metadata.json",
    "REVIEW.md",
)
YOUTUBE_TITLE_LIMIT = 100
YOUTUBE_DESCRIPTION_LIMIT = 5000
YOUTUBE_TAG_BUDGET = 500
YOUTUBE_CATEGORY = "24"


class PackageError(RuntimeError):
    """Raised when a package cannot be written."""


def _normalize(value: str) -> str:
    return " ".join(value.split()).strip()


def _clip(value: str, limit: int) -> str:
    if limit < 1:
        raise ValueError("limit must be at least 1")
    if len(value) <= limit:
        return value
    if limit <= 3:
        return value[:limit]
    cut = value[: limit - 3]
    clipped = cut.rsplit(" ", 1)[0].rstrip(" ,.;:")
    return f"{clipped}..." if clipped else f"{cut}..."


def slugify(value: str, *, max_length: int = 60) -> str:
    """Turn a headline into a filesystem-safe directory name."""

    ascii_value = unicodedata.normalize("NFKD", value).encode("ascii", "ignore").decode()
    slug = re.sub(r"[^a-z0-9]+", "-", ascii_value.lower()).strip("-")
    return slug[:max_length].rstrip("-") or "package"


def youtube_title(headline: Headline) -> str:
    """Return a title that fits the YouTube 100-character limit."""

    suffix = " #Shorts"
    title = _normalize(headline.title) or "THE NEWS"
    return _clip(title, YOUTUBE_TITLE_LIMIT - len(suffix)) + suffix


def youtube_description(headline: Headline) -> str:
    """Return a review-first description with source attribution."""

    source = _normalize(headline.source) or "unknown source"
    description = (
        f"{_normalize(headline.title)}\n\n"
        f"Source: {source}\n\n"
        "Generated by NewsMemeAI YouTube for human review. "
        "This package is not published automatically.\n\n"
        "#Shorts #News #Memes"
    )
    return _clip(description, YOUTUBE_DESCRIPTION_LIMIT)


def youtube_tags(headline: Headline) -> list[str]:
    """Return a small tag set that stays inside YouTube's 500-character budget."""

    tags = ["shorts", "news", "memes", "newsmemeai", "news meme"]
    source = _normalize(headline.source)
    if source.startswith(("http://", "https://")):
        host = urlparse(source).hostname or ""
        if host:
            tags.append(host.removeprefix("www."))
    else:
        tags.append("local news")

    budget = 0
    for tag in tags:
        budget += len(tag) + 1
        if budget > YOUTUBE_TAG_BUDGET:
            raise PackageError("tag budget exceeded")
    return tags


def youtube_metadata(headline: Headline) -> dict[str, object]:
    """Return the metadata.json payload."""

    return {
        "schema_version": 1,
        "title": youtube_title(headline),
        "description": youtube_description(headline),
        "tags": youtube_tags(headline),
        "category_id": YOUTUBE_CATEGORY,
        "privacy_status": "private",
        "made_for_kids": False,
        "shorts": True,
    }


def _md_cell(value: str) -> str:
    return _normalize(value).replace("|", "\\|")


def _script_markdown(headline: Headline, script: Script) -> str:
    source = _normalize(headline.source) or "unknown source"
    return (
        f"# Shorts Script — {_md_cell(headline.title)}\n\n"
        f"**Source:** {_md_cell(source)}\n"
        f"**Headline:** {_md_cell(headline.title)}\n"
        f"**Style:** {_md_cell(script.style)}\n"
        f"**Model:** {_md_cell(script.model)}\n"
        "**Review status:** draft\n\n"
        "| Beat | Time | On-screen text | Voiceover |\n"
        "| --- | --- | --- | --- |\n"
        f"| Hook | 0–3s | {_md_cell(script.hook)} | {_md_cell(script.hook)} |\n"
        f"| Context | 3–8s | {_md_cell(script.context)} | {_md_cell(script.context)} |\n"
        f"| Punchline | 8–12s | {_md_cell(script.punchline)} | {_md_cell(script.punchline)} |\n\n"
        "## Editorial rationale\n\n"
        f"{_md_cell(script.rationale or 'No rationale provided.')}\n\n"
        "## Production notes\n\n"
        "- Use the three vertical frames as storyboard beats.\n"
        "- Use `thumbnail.svg` for the 1280x720 thumbnail.\n"
        "- Export the final video with a human editor before upload.\n"
        "- This package is private and must not be published automatically.\n"
    )


def _review_markdown(headline: Headline) -> str:
    return (
        f"# Human Review — {_md_cell(headline.title)}\n\n"
        "Mark every item before publishing. Any unchecked item blocks release.\n\n"
        "- [ ] The hook and punchline do not assert new facts.\n"
        "- [ ] The context matches the headline and summary.\n"
        "- [ ] No numbers, names, or quotes were invented.\n"
        "- [ ] Metadata title, description, and tags are appropriate.\n"
        "- [ ] Frames and thumbnail are legible on a phone.\n"
        "- [ ] The package is still private; nothing was auto-published.\n\n"
        "**Hallucination debt:** 0 open claims\n"
        "**Reviewer:**\n"
        "**Review date:**\n"
        "**Decision:** draft / approved / rejected\n"
    )


def _write_json(path: Path, payload: object) -> None:
    path.write_text(
        json.dumps(payload, indent=2, sort_keys=True, ensure_ascii=False) + "\n",
        encoding="utf-8",
    )


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _file_entry(path: Path) -> dict[str, object]:
    return {"sha256": _sha256(path), "bytes": path.stat().st_size}


def build_package(
    headline: Headline,
    script: Script,
    out_dir: str | Path,
    *,
    style: str = "classic",
) -> Path:
    """Write every artifact and return the package directory."""

    destination = Path(out_dir).expanduser()
    try:
        destination.mkdir(parents=True, exist_ok=True)
    except OSError as exc:
        raise PackageError(f"could not create package directory: {exc}") from exc

    write_svg(
        destination / "frame-01-hook.svg",
        render_story_frame(
            kicker="hook",
            title=script.hook,
            footer=_normalize(headline.source),
            index=1,
        ),
    )
    write_svg(
        destination / "frame-02-context.svg",
        render_story_frame(
            kicker="context",
            title=script.context,
            footer=_normalize(headline.source),
            index=2,
        ),
    )
    write_svg(
        destination / "frame-03-punchline.svg",
        render_story_frame(
            kicker="punchline",
            title=script.punchline,
            footer="FOLLOW FOR MORE // NEWSMEMEAI",
            index=3,
        ),
    )
    write_svg(
        destination / "thumbnail.svg",
        render_thumbnail(title=headline.title, footer=_normalize(headline.source)),
    )
    (destination / "script.md").write_text(_script_markdown(headline, script), encoding="utf-8")
    _write_json(destination / "metadata.json", youtube_metadata(headline))
    (destination / "REVIEW.md").write_text(_review_markdown(headline), encoding="utf-8")

    files = {
        name: _file_entry(destination / name)
        for name in sorted(REQUIRED_ARTIFACTS)
        if (destination / name).is_file()
    }
    manifest = {
        "schema_version": PACKAGE_SCHEMA_VERSION,
        "generator": {"name": GENERATOR_NAME, "version": __version__},
        "style": style,
        "headline": asdict(headline),
        "script": asdict(script),
        "review": {
            "status": "draft",
            "required": True,
            "checklist": "REVIEW.md",
        },
        "dimensions": {
            "frame": [VERTICAL_WIDTH, VERTICAL_HEIGHT],
            "thumbnail": [THUMBNAIL_WIDTH, THUMBNAIL_HEIGHT],
        },
        "files": files,
    }
    _write_json(destination / "manifest.json", manifest)
    return destination
